"""Ошибки приложения с понятными пользователю текстами.

Все исключения проекта наследуются от AppError. Благодаря этому в интерфейсе
достаточно поймать один тип исключения и показать его текст как есть.
"""


class AppError(Exception):
    """Базовая ошибка: сообщение можно показывать пользователю без правок."""


class ProductDataError(AppError):
    """Данные товара пустые, неполные или имеют неверный формат."""


class LLMError(AppError):
    """Проблема при обращении к LLM: ключ, сеть, таймаут, пустой ответ."""


class ResponseFormatError(AppError):
    """Ответ модели не удалось разобрать или он не соответствует структуре."""
